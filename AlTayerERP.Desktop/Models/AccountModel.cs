using System;

namespace AlTayerERP.Desktop.Models
{
    /// <summary>
    /// النموذج المحاسبي المعتمد لتمثيل بيانات الحساب المالي في دليل الحسابات (Chart of Accounts)
    /// </summary>
    public class AccountModel
    {
        // ==========================================
        // أولاً: معرفات الحساب والربط الهيكلي
        // ==========================================

        // المعرف الفريد للحساب في قاعدة البيانات (GUID أو قيم تسلسلية)
        public string Account_ID { get; set; } = "";

        // معرف الشركة المالي لربط الدليل بشركة محددة داخل النظام
        public string Company_ID { get; set; } = "";

        // معرف الحساب الأب؛ يكون فارغاً (null) إذا كان الحساب في أعلى الشجرة كحساب رئيسي
        public string? Parent_Account_ID { get; set; }


        // ==========================================
        // ثانياً: البيانات الأساسية للحساب المحاسبي
        // ==========================================

        // الرقم المالي للحساب المحاسبي (مثل: 1, 11, 1101) وهو المعتمد في شجرة الترقيم
        public string Account_Code { get; set; } = "";

        // اسم الحساب باللغة العربية (إلزامي للتقارير والمعاملات المحلية)
        public string Account_Name_AR { get; set; } = "";

        // اسم الحساب باللغة الإنجليزية (اختياري للتقارير والواجهات ثنائية اللغة)
        public string? Account_Name_EN { get; set; }


        // ==========================================
        // ثالثاً: التصنيفات المحاسبية والمستويات
        // ==========================================

        // نوع الحساب المالي (Asset/أصل، Liability/خصم، Equity/حقوق ملكية، Revenue/إيراد، Expense/مصروف)
        public string Account_Type { get; set; } = "";

        // تصنيف الحساب المساعد (نقدية، بنك، عميل، مورد... إلخ) لتسهيل فلترة التقارير
        public string? Account_Category { get; set; }

        // طبيعة الحساب المالية؛ هل هو حساب (مدين) بطبيعته أم حساب (دائن)
        public string? Normal_Balance { get; set; }

        // رتبة الحساب في الشجرة (المستوى 1 للحسابات الرئيسية، المستوى 2 للحسابات المتفرعة عنها، وهكذا)
        public int Account_Level { get; set; }


        // ==========================================
        // رابعاً: محددات حالة الحساب والعملة
        // ==========================================

        // هل الحساب قابل للترحيل؟ (True تعني حساب فرعي تقبل عليه القيود، False تعني حساب رئيسي تجميعي فقط)
        public bool Is_Postable { get; set; }

        // حالة الحساب في النظام (نشط لتمرير القيود عليه، أو موقوف لتجميد التعامل معه)
        public bool Is_Active { get; set; }

        // رمز العملة الافتراضية للحساب (مثل: YER, SAR, USD)
        public string? Currency_Code { get; set; }

        // ملاحظات وتفاصيل إضافية يكتبها المحاسب عن طبيعة استخدام هذا الحساب
        public string? Notes { get; set; }


        // ==========================================
        // خامساً: محددات الشروط القيود والميزات المتقدمة (الـ CheckBoxes)
        // ==========================================

        // يتيح للمستخدم إدخال رقم الحساب يدوياً بدلاً من التوليد الآلي للنظام
        public bool Allow_ManualEntry { get; set; }

        // حساب خاص بالنظام؛ يتم حمايته من الحذف أو التعديل العشوائي لأنه مرتبط بعمليات آلية
        public bool System_Account { get; set; }

        // يشترط تحديد جهة تعامل (عميل، مورد، موظف) عند عمل قيد يومية على هذا الحساب
        public bool Requires_Party { get; set; }

        // يشترط ربط الحساب بمركز تكلفة (Cost Center) عند إجراء أي حركة مالية
        public bool Requires_CostCenter { get; set; }

        // يشترط ربط الحساب بمشروع محدد عند تسجيل العمليات المالية
        public bool Requires_Project { get; set; }

        // يحدد أن هذا الحساب هو حساب تجميعي/خلاصة (Summary) للحسابات التابعة له
        public bool Is_Summary_Account { get; set; }

        // يحدد هل يؤثر الحساب ويظهر ضمن تقرير الميزانية العمومية (Balance Sheet)
        public bool Affects_Balance_Sheet { get; set; }

        // يحدد هل يؤثر الحساب ويظهر ضمن تقرير قائمة الدخل (Income Statement)
        public bool Affects_Income_Statement { get; set; }

        // يسمح للحساب بفتح وقبول حركات مالية بعدة عملات مختلفة وليس بالعملة الافتراضية فقط
        public bool Multi_Currency { get; set; }


        // ==========================================
        // سادساً: حقول التتبع، الترتيب، والرقابة الأمنية
        // ==========================================

        // المسار الكامل للحساب بالشجرة (مثل: 1/11/1101) لتسهيل عمليات الاستعلام السريعة في قواعد البيانات
        public string? Account_Path { get; set; }

        // الرقم التسلسلي للحساب ضمن نفس المستوى البرمجي لتأمين الترتيب الصحيح
        public int? Account_Serial { get; set; }

        // اسم المستخدم أو المحاسب الذي قام بإنشاء هذا الحساب لأول مرة
        public string? Created_By { get; set; }

        // تاريخ ووقت آخر عملية تعديل أو تحديث جرت على بيانات الحساب
        public DateTime? Updated_At { get; set; }

        // اسم المستخدم الذي قام بإجراء آخر عملية تعديل على الحساب
        public string? Updated_By { get; set; }
    }
}